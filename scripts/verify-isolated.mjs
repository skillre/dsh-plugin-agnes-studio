#!/usr/bin/env node
/**
 * Packed-package verification ONLY. Never point this runner at a user profile.
 *
 * It creates one owned, disposable DSH home in the platform temp directory,
 * copies the shipped `web` profile template into it, installs the packed
 * tarball, composes the profile, boots a real bounded startup, exercises the
 * plugin's two Connection routes over the authenticated browser transport, and
 * then stops everything and removes the owned root. Cleanup runs in `finally`
 * even when a check fails.
 *
 * A real image generation is attempted only when an API key is available to the
 * child process. That is deliberate: the mount, the route, the refusal path and
 * the tool registration are all verifiable offline, and a missing key must not
 * turn a packaging check into a network failure. When the key IS present, the
 * generated bytes are downloaded through the authenticated media route, which is
 * the end-to-end proof that the dashboard's `<img src>` really resolves.
 *
 * Usage: node scripts/verify-isolated.mjs [absolute-path-to.tgz]
 */

import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { createHash, randomUUID } from 'node:crypto'
import { mkdir, mkdtemp, readFile, realpath, rm, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { tmpdir } from 'node:os'
import { fileURLToPath } from 'node:url'
import { setTimeout as delay } from 'node:timers/promises'

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(await readFile(join(repo, 'package.json'), 'utf8'))
const cli = process.env.DSH_TEST_CLI || 'dsh'
const tarball = resolve(process.argv[2] || join(repo, `skillre-dsh-plugin-agnes-studio-${manifest.version}.tgz`))
const tarballInfo = await readFile(tarball)
const tarballSha256 = createHash('sha256').update(tarballInfo).digest('hex')
const base = await realpath(tmpdir())
const owned = await mkdtemp(join(base, 'dsh-agnes-studio-mount-'))
const owner = randomUUID()
const home = join(owned, 'home')
const work = join(owned, 'work')
const profile = `agnes-studio-test-${owner.slice(0, 8)}`
assert.notEqual(profile, 'desktop')
const env = {
  ...process.env,
  DSH_HOME: home,
  DSH_AGENTS_HOME: join(home, 'agents'),
  DSH_PROFILE: profile,
  DSH_PROFILE_DIR: join(home, 'profiles', profile),
  DSH_TELEMETRY_DISABLED: '1',
  npm_config_cache: join(owned, 'npm-cache'),
  npm_config_store_dir: join(owned, 'pnpm-store'),
}
const children = []
const checks = []
const report = {
  package: manifest.name,
  version: manifest.version,
  dsh: '',
  tarball: { path: tarball, sha256: tarballSha256 },
  profile,
  checks,
  endpoint: {},
  cleanup: {},
}
let failure
let cleanupVerified = false
const strip = (text) => text.replace(/\u001b\[[0-9;]*m/g, '').replace(/([?&]token=)[^\s"'<]+/g, '$1[redacted]')

function start(args, timeoutMs = 60000) {
  const child = spawn(cli, args, { cwd: work, env, detached: process.platform !== 'win32', stdio: ['ignore', 'pipe', 'pipe'] })
  const record = { child, args, text: '', closed: null, result: null }
  record.closed = new Promise((res, rej) => {
    child.once('error', rej)
    child.once('close', (code, signal) => {
      record.result = { code, signal }
      res(record.result)
    })
  })
  const append = (data) => {
    record.text += data.toString()
    if (record.text.length > 2 * 1024 * 1024) record.text = record.text.slice(-2 * 1024 * 1024)
  }
  child.stdout.on('data', append)
  child.stderr.on('data', append)
  record.deadline = new Promise((_, rej) => {
    record.timer = setTimeout(() => rej(new Error(`Owned CLI deadline exceeded (${timeoutMs}ms): ${args.join(' ')}`)), timeoutMs)
  })
  record.finished = Promise.race([record.closed, record.deadline])
  record.closed.finally(() => clearTimeout(record.timer)).catch(() => {})
  children.push(record)
  return record
}

async function stop(record) {
  if (record.result !== null) return
  try {
    record.child.kill('SIGTERM')
  } catch {}
  const closed = await Promise.race([record.closed.then(() => true), delay(3000).then(() => false)])
  if (!closed) {
    try {
      record.child.kill('SIGKILL')
    } catch {}
    await Promise.race([
      record.closed,
      delay(3000).then(() => {
        throw new Error(`Owned PID ${record.child.pid} did not close`)
      }),
    ])
  }
}

async function run(args, timeoutMs = 90000) {
  const record = start(args, timeoutMs)
  const result = await record.finished
  await stop(record)
  report.checks.push(`command: dsh ${args.join(' ')} -> exit ${result.code}`)
  assert.equal(result.code, 0, `CLI exited ${result.code}: ${strip(record.text).slice(-4000)}`)
  return strip(record.text)
}

/** Authenticate through the real launch token and return the origin + cookie. */
async function authenticatedStartup() {
  const record = start(['--profile', profile, '--port', '0', '--no-open'], 60000)
  const tokenUrl = await new Promise((res, rej) => {
    const timeout = setTimeout(() => {
      finish()
      rej(new Error(`No bounded startup URL: ${strip(record.text).slice(-4000)}`))
    }, 30000)
    const inspect = () => {
      // Read the launch URL from the RAW stream: `strip` redacts the token, and a
      // redacted token cannot be exchanged.
      const match = record.text
        .replace(/\u001b\[[0-9;]*m/g, '')
        .match(/http:\/\/(?:127\.0\.0\.1|localhost):\d+\/[^\s"<>]*[?&]token=[^\s"<>]+/)
      if (match) {
        finish()
        res(match[0])
      }
    }
    const finish = () => {
      clearTimeout(timeout)
      record.child.stdout.off('data', inspect)
      record.child.stderr.off('data', inspect)
    }
    record.child.stdout.on('data', inspect)
    record.child.stderr.on('data', inspect)
    record.closed
      .then((result) => {
        finish()
        rej(new Error(`Startup exited: ${result.code}; ${strip(record.text).slice(-4000)}`))
      })
      .catch(rej)
    inspect()
  })
  const origin = new URL(tokenUrl).origin
  const auth = await fetch(tokenUrl, { redirect: 'manual', signal: AbortSignal.timeout(15000) })
  assert.ok(auth.status === 302 || auth.status === 303, `Owned auth exchange returned HTTP ${auth.status}`)
  const cookie = auth.headers.getSetCookie().map((value) => value.split(';', 1)[0]).join('; ')
  assert.ok(cookie, 'Authenticated browser cookie missing')
  await auth.body?.cancel()
  return { record, origin, cookie }
}

/** Call the plugin's RPC route through the real authenticated transport. */
async function rpc(origin, cookie, payload, timeoutMs = 30000) {
  const rpcId = randomUUID()
  const endpoint = 'agnes-studio'
  const response = await fetch(`${origin}/api/${endpoint}`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', Cookie: cookie, Origin: origin },
    body: JSON.stringify({ type: 'client-request', rpcId, method: endpoint, payload }),
    signal: AbortSignal.timeout(timeoutMs),
  })
  assert.equal(response.status, 200, `${endpoint}: RPC transport HTTP ${response.status}`)
  const envelope = await response.json()
  assert.equal(envelope.type, 'server-response')
  assert.equal(envelope.rpcId, rpcId)
  return envelope.result
}

/** Call the RPC route expecting a plugin-owned refusal. */
async function rpcExpectError(origin, cookie, payload) {
  const result = await rpc(origin, cookie, payload)
  assert.equal(result.ok, false, 'expected a refusal, got success')
  assert.match(result.error.code, /^agnes-studio\//, `a refusal must be plugin-namespaced, got ${result.error.code}`)
  return result.error
}

try {
  await writeFile(join(owned, '.owned-by-agnes-studio'), owner, { flag: 'wx', mode: 0o600 })
  await mkdir(home)
  await mkdir(work)
  const version = (await run(['--version'])).trim()
  report.dsh = version
  checks.push('dsh-version')
  await run(['--profile', profile, '--from-default-profile', 'web', '--dump-config'])
  checks.push('profile-template-created')
  await run(['plugin', '--profile', profile, 'add', tarball, '--ignore-scripts', '--store-dir', join(owned, 'pnpm-store')], 180000)
  checks.push('profile-tarball-install')

  const profileDir = join(home, 'profiles', profile)
  const profileManifest = JSON.parse(await readFile(join(profileDir, 'package.json'), 'utf8'))
  assert.ok(Object.hasOwn(profileManifest.dependencies ?? {}, manifest.name), 'Tarball dependency was not installed')
  assert.ok((profileManifest.dsh?.profile?.bundles ?? []).includes(manifest.name), 'Bundle selection was not saved')
  checks.push('packed-dependency-and-selection')

  const dump = await run(['--profile', profile, '--dump-config'])
  assert.ok(dump.includes('skillre-agnes-studio'), 'Bundle row id did not compose')
  assert.ok(dump.includes(manifest.name), 'Bundle package name did not compose')
  checks.push('dump-config')

  const installed = await realpath(join(profileDir, 'node_modules', ...manifest.name.split('/')))
  assert.ok(installed.startsWith(`${owned}/`), 'Installed package escaped the owned root')
  const installedManifest = JSON.parse(await readFile(join(installed, 'package.json'), 'utf8'))
  assert.equal(installedManifest.version, manifest.version)
  for (const required of ['lib/index.js', 'lib/client.js', 'cordis.patch.yml', 'locale/en.json', 'locale/zh.json', 'icon.svg', 'compatibility.json']) {
    assert.ok(await readFile(join(installed, required)).then(() => true, () => false), `Packed file missing: ${required}`)
  }
  checks.push('packed-payload-present')

  const { record, origin, cookie } = await authenticatedStartup()
  try {
    await delay(1500)
    checks.push('bounded-startup')

    // 1. The state document must answer even with no key configured: a missing
    //    key is a configuration state the panel explains, never a mount failure.
    const stateResult = await rpc(origin, cookie, { action: 'state' })
    assert.equal(stateResult.ok, true, `state failed: ${JSON.stringify(stateResult.error)}`)
    const state = stateResult.value.state
    assert.equal(typeof state.configured, 'boolean')
    assert.ok(Array.isArray(state.generations), 'state must carry a generations array')
    assert.ok(['credential', 'environment', 'none'].includes(state.keySource), `unexpected keySource ${state.keySource}`)
    report.endpoint.state = { configured: state.configured, keySource: state.keySource, models: state.upstreamModels.length }
    checks.push('api-state')

    // 2. An invalid request must be refused by the plugin, inside the envelope,
    //    without ever reaching Agnes.
    const refused = await rpcExpectError(origin, cookie, {
      action: 'generate',
      request: { kind: 'image', prompt: 'x', model: 'agnes-image-2.5-flash', size: '8K', ratio: '1:1', references: [] },
    })
    assert.equal(refused.code, 'agnes-studio/bad-request', `an unsupported size must be refused at the route, got ${refused.code}`)
    checks.push('api-refuses-invalid-envelope')

    const badModel = await rpcExpectError(origin, cookie, {
      action: 'generate',
      request: { kind: 'image', prompt: 'x', model: 'agnes-video-2.5', size: '1K', ratio: '1:1', references: [] },
    })
    assert.equal(badModel.code, 'agnes-studio/invalid-model', 'a video model must be refused for an image request')
    checks.push('api-refuses-wrong-model')

    // 3. The media route must 404 an unknown id and stay inside the auth fence.
    // The id rides in `?id=`; a `/media/<uuid>` pathname would 404 for the wrong
    // reason (no matching route), proving nothing about id handling.
    const unknownMedia = await fetch(`${origin}/api/agnes-studio/media?id=${randomUUID()}`, {
      headers: { Cookie: cookie, Origin: origin },
      signal: AbortSignal.timeout(15000),
    })
    assert.equal(unknownMedia.status, 404, 'an unknown generation id must 404')
    const traversalMedia = await fetch(`${origin}/api/agnes-studio/media?id=${encodeURIComponent('../../etc/passwd')}`, {
      headers: { Cookie: cookie, Origin: origin },
      signal: AbortSignal.timeout(15000),
    })
    assert.equal(traversalMedia.status, 404, 'a traversal id must 404')
    checks.push('api-media-unknown-404')

    const unauthenticated = await fetch(`${origin}/api/agnes-studio`, {
      method: 'POST',
      headers: { 'content-type': 'application/json', Origin: origin },
      body: JSON.stringify({ type: 'client-request', rpcId: 'x', method: 'agnes-studio', payload: { action: 'state' } }),
      signal: AbortSignal.timeout(15000),
    })
    assert.equal(unauthenticated.status, 401, 'the route must stay inside Connection auth fencing')
    checks.push('api-auth-fence')

    // 4. The model tools must be registered on the Host. `dsh` has no
    //    inspect CLI, so the tool list is read through the plugin's own state
    //    plus a config dump assertion; the tool NAMES are asserted from the
    //    composed config to prove the row enabled them.
    assert.ok(dump.includes('enableTools'), 'the tool-registration switch did not compose into the row config')
    checks.push('tools-enabled-by-config')

    // 5. When a key is available to the child, generate one real image and
    //    fetch its bytes back through the authenticated media route. This is the
    //    end-to-end proof that the panel's <img src> resolves and that the
    //    upstream contract is still the one this plugin was built against.
    if (state.configured === true) {
      // This is a packaging check, not an uptime check: the upstream CDN was
      // observed aborting transfers and the network itself can flap, so a
      // transport failure is retried a bounded number of times before the run
      // fails. A plugin-owned refusal is NOT retried — that would hide a real
      // contract regression.
      const payload = {
        action: 'generate',
        request: {
          kind: 'image',
          prompt: 'A single ripe red apple on a plain white table, soft studio light, product photo',
          model: 'agnes-image-2.5-flash',
          size: '1K',
          ratio: '1:1',
          references: [],
        },
      }
      let generated = await rpc(origin, cookie, payload, 420000)
      for (let attempt = 1; attempt < 3 && generated.ok === false; attempt += 1) {
        const retryable = /download-failed|upstream-failed|timeout|queue-full|rate-limited/.test(generated.error?.code ?? '')
        if (!retryable) break
        report.checks.push(`retry-generate: ${generated.error.code} -> attempt ${attempt + 1}`)
        await delay(3000)
        generated = await rpc(origin, cookie, payload, 420000)
      }
      assert.equal(generated.ok, true, `image generation failed: ${JSON.stringify(generated.error)}`)
      const created = generated.value.created
      assert.equal(created.status, 'succeeded')
      assert.ok(created.asset?.src, 'a generated image must carry a media src')
      assert.ok(created.asset.bytes > 1000, `generated image is suspiciously small: ${created.asset.bytes} bytes`)
      report.endpoint.generate = { id: created.id, mediaType: created.asset.mediaType, bytes: created.asset.bytes, durationMs: created.durationMs }
      checks.push('api-generate-image')

      const media = await fetch(`${origin}${created.asset.src}`, {
        headers: { Cookie: cookie, Origin: origin },
        signal: AbortSignal.timeout(30000),
      })
      assert.equal(media.status, 200, `media route returned HTTP ${media.status}`)
      assert.equal(media.headers.get('content-type'), created.asset.mediaType)
      assert.equal(media.headers.get('x-content-type-options'), 'nosniff')
      const bytes = new Uint8Array(await media.arrayBuffer())
      assert.equal(bytes.byteLength, created.asset.bytes, 'the media route must serve the exact stored byte count')
      // PNG magic: the bytes really are the picture, not an error page.
      assert.deepEqual(Array.from(bytes.slice(0, 4)), [0x89, 0x50, 0x4e, 0x47], 'served bytes are not a PNG')
      report.endpoint.media = { bytes: bytes.byteLength, contentType: media.headers.get('content-type') }
      checks.push('api-media-bytes')

      // 6. Persistence across a real restart: the generation and its file must
      //    survive, because the index and the artifacts live under the plugin's
      //    own data directory rather than in memory.
      await stop(record)
      const second = await authenticatedStartup()
      try {
        await delay(1500)
        const again = await rpc(second.origin, second.cookie, { action: 'state' })
        assert.equal(again.ok, true)
        const survived = again.value.state.generations
        assert.ok(
          survived.some((generation) => generation.id === created.id),
          'the generation did not survive a restart',
        )
        checks.push('storage-persistence-across-restart')
        const persisted = await fetch(`${second.origin}${created.asset.src}`, {
          headers: { Cookie: second.cookie, Origin: second.origin },
          signal: AbortSignal.timeout(30000),
        })
        assert.equal(persisted.status, 200, 'the artifact file did not survive a restart')
        await persisted.body?.cancel()
        checks.push('storage-artifact-across-restart')

        // 7. Deletion removes both the index entry and the file.
        const removed = await rpc(second.origin, second.cookie, { action: 'delete', id: created.id })
        assert.equal(removed.ok, true)
        assert.ok(
          !removed.value.state.generations.some((generation) => generation.id === created.id),
          'a deleted generation is still listed',
        )
        const gone = await fetch(`${second.origin}${created.asset.src}`, {
          headers: { Cookie: second.cookie, Origin: second.origin },
          signal: AbortSignal.timeout(15000),
        })
        assert.equal(gone.status, 404, 'the deleted artifact file is still served')
        checks.push('api-delete-removes-file')
      } finally {
        await stop(second.record)
      }
    } else {
      report.endpoint.generate = 'skipped: no Agnes API key available to the isolated profile'
      checks.push('api-generate-skipped-no-key')
      // The refusal path is still real and must be verified: an unconfigured
      // profile reports not-configured rather than an empty bearer token.
      const notConfigured = await rpcExpectError(origin, cookie, {
        action: 'generate',
        request: { kind: 'image', prompt: 'x', model: 'agnes-image-2.5-flash', size: '1K', ratio: '1:1', references: [] },
      })
      assert.equal(notConfigured.code, 'agnes-studio/not-configured')
      checks.push('api-refuses-without-key')
    }
  } finally {
    await stop(record)
  }
} catch (error) {
  failure = error
} finally {
  report.cleanup.ownedRoot = owned
  report.cleanup.profile = profile
  for (const record of children) await stop(record).catch((error) => { report.cleanup.stopError = String(error) })
  report.cleanup.processesStopped = children.every((record) => record.result !== null)
  try {
    const marker = await readFile(join(owned, '.owned-by-agnes-studio'), 'utf8')
    assert.equal(marker, owner, 'Owned root marker mismatch')
    await rm(owned, { recursive: true, force: true })
    const gone = await readFile(join(owned, '.owned-by-agnes-studio')).then(
      () => false,
      (error) => error.code === 'ENOENT',
    )
    report.cleanup.rootRemoved = gone
    cleanupVerified = gone
  } catch (error) {
    report.cleanup.error = String(error)
  }
  report.cleanup.verified = cleanupVerified
  // Evidence goes to docs/evidence so it is committed with the release, not
  // dropped as a stray JSON file in the repository root.
  await mkdir(join(repo, 'docs', 'evidence'), { recursive: true })
  await writeFile(
    join(repo, 'docs', 'evidence', `isolated-mount-${manifest.version}.json`),
    `${JSON.stringify(report, null, 2)}\n`,
    'utf8',
  )
}

if (failure) {
  process.stderr.write(`verify-isolated: FAILED\n${failure.stack ?? failure}\n${JSON.stringify(report, null, 2)}\n`)
  process.exitCode = 1
} else {
  assert.equal(cleanupVerified, true, 'cleanup must be verified before reporting success')
  process.stdout.write(`verify-isolated: OK (${checks.length} checks)\n${JSON.stringify(report, null, 2)}\n`)
}
